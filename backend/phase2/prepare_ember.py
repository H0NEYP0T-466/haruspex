#!/usr/bin/env python3
"""Prepare EMBER 2018 — vectorize raw JSONL feature files into .dat memmaps.

Run this ONCE before train_ember.py. It converts the raw EMBER JSONL files
(train_features_*.jsonl) into fast numpy memmap files (X_train.dat, y_train.dat)
that can be loaded instantly for training.

Usage:
    cd backend
    source venv/bin/activate       # or .venv
    python phase2/prepare_ember.py

The X_test.dat / y_test.dat files should already exist (generated by
scripts/prepare_ember.py). This script generates/repairs the train memmaps.

Safety guarantees:
    - Vectorization writes to *.dat.tmp files and atomically renames them on
      success, so an interrupted run never leaves corrupt placeholders behind.
    - Existing memmaps are validated (label mix + row count) before being
      trusted; artifacts of a crashed earlier run are detected and regenerated.

Expected time:
    ~30-60 min on i7-6500U (800K samples)
    ~10-15 min on Kaggle / modern CPU
"""

from __future__ import annotations

import os
import sys
import time
from pathlib import Path

import numpy as np

# Add backend/ to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from haruspex.config import BACKEND_DIR, NUM_FEATURES
from haruspex.data import ember as ember_mod
from haruspex.data.ember import vectorize_partition
from haruspex.utils.logging import get_logger

logger = get_logger(__name__)

EMBER_DIR = BACKEND_DIR / "dataset" / "ember2018"


def validate_dat_pair(
    x_path: Path,
    y_path: Path,
    expected_rows: int | None = None,
    feature_dim: int | None = None,
) -> tuple[bool, str]:
    """Check that a vectorized .dat pair contains real, usable data.

    A legitimate EMBER partition always contains BOTH classes. A label file
    where every entry is identical (typically all 0.0 from zero-filled
    pre-allocation) indicates a crashed/interrupted vectorization run.

    If both expected_rows and feature_dim are given, the X file size is also
    verified against rows * dim * sizeof(float32).
    """
    try:
        y = np.memmap(str(y_path), dtype=np.float32, mode="r")
    except ValueError as e:
        return False, f"cannot read {y_path.name}: {e}"

    n = int(y.size)
    if n == 0:
        return False, f"{y_path.name} is empty"

    if expected_rows is not None and n != expected_rows:
        return False, f"{y_path.name} has {n:,} rows, expected {expected_rows:,}"

    if expected_rows is not None and feature_dim is not None:
        need = expected_rows * feature_dim * 4
        got = x_path.stat().st_size
        if got != need:
            return False, (
                f"{x_path.name} is {got:,} bytes, expected {need:,}"
            )

    n_benign = int(np.sum(y == 0))
    n_malware = int(np.sum(y == 1))
    n_unlabeled = int(np.sum(y == -1))

    if n_benign == 0 or n_malware == 0:
        return False, (
            f"{y_path.name} looks like a crashed/incomplete vectorization "
            f"(benign={n_benign:,}, malware={n_malware:,}, unlabeled={n_unlabeled:,})"
        )

    return True, (
        f"{y_path.name}: {n_benign:,} benign / {n_malware:,} malware / "
        f"{n_unlabeled:,} unlabeled"
    )


def _cleanup(paths: list[Path]) -> None:
    for p in paths:
        p.unlink(missing_ok=True)


def main() -> int:
    """Vectorize EMBER train partition JSONL -> .dat memmaps."""
    print("=" * 72)
    print("  EMBER 2018 — Vectorize Train Partition")
    print("=" * 72)

    if not EMBER_DIR.exists():
        print(f"\n  ERROR: EMBER directory not found: {EMBER_DIR}")
        print("  Download EMBER 2018 and place files in backend/dataset/ember2018/")
        return 1

    train_jsonls = sorted(EMBER_DIR.glob("train_features_*.jsonl"))
    if not train_jsonls:
        print(f"\n  ERROR: No train_features_*.jsonl files found in {EMBER_DIR}")
        return 1

    print(f"\n  Found {len(train_jsonls)} train JSONL files:")
    for p in train_jsonls:
        print(f"    {p.name} ({p.stat().st_size / (1024 * 1024):.0f} MB)")

    x_train_dat = EMBER_DIR / "X_train.dat"
    y_train_dat = EMBER_DIR / "y_train.dat"

    # Skip re-vectorization ONLY when the existing pair validates as real data.
    if x_train_dat.exists() and y_train_dat.exists():
        ok, msg = validate_dat_pair(x_train_dat, y_train_dat)
        if ok:
            print(f"\n  Train memmaps already exist and are valid ({msg}).")
            print("  Delete them manually to re-vectorize.")
            return 0
        print("\n  Existing train memmaps are INVALID — regenerating:")
        print(f"    ({msg})")

    # Sanity-check the test pair too (warn only; cross-dataset eval uses it).
    x_test_dat = EMBER_DIR / "X_test.dat"
    y_test_dat = EMBER_DIR / "y_test.dat"
    if y_test_dat.exists():
        ok, msg = validate_dat_pair(
            x_test_dat, y_test_dat, expected_rows=200_000, feature_dim=NUM_FEATURES
        )
        print(f"\n  Test memmaps: {'OK' if ok else 'INVALID'} ({msg})")

    # Vectorize into temporary files so a crash cannot leave placeholders.
    x_tmp = x_train_dat.with_suffix(".dat.tmp")
    y_tmp = y_train_dat.with_suffix(".dat.tmp")
    _cleanup([x_tmp, y_tmp])

    print(f"\n  Starting train vectorization ({len(train_jsonls)} files)...")
    print("  This will take 30-60 minutes on a laptop CPU.\n")

    t0 = time.time()
    try:
        nrows = vectorize_partition(train_jsonls, x_tmp, y_tmp, log_every=10_000)
    except BaseException:
        _cleanup([x_tmp, y_tmp])
        print("\n  Vectorization FAILED — temporary files removed. No corruption left behind.")
        raise

    elapsed = time.time() - t0

    feature_dim = ember_mod._get_extractor().dim
    ok, msg = validate_dat_pair(x_tmp, y_tmp, expected_rows=nrows, feature_dim=feature_dim)
    if not ok:
        _cleanup([x_tmp, y_tmp])
        print(f"\n  ERROR: vectorized output failed validation: {msg}")
        print("  Temporary files removed — please re-run this script.")
        return 1

    os.replace(x_tmp, x_train_dat)
    os.replace(y_tmp, y_train_dat)

    print(f"\n  Done! Validated and installed in {elapsed:.1f}s ({elapsed / 60:.1f} min)")
    print(f"  Output: {x_train_dat} ({x_train_dat.stat().st_size / 1e9:.2f} GB)")
    print(f"          {y_train_dat} ({y_train_dat.stat().st_size / 1e6:.1f} MB)")
    print(f"  Labels: {msg}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
